#!/usr/bin/env bash
# ============================================================================
# backup-tfstate.sh — สำรอง state ของ Terraform ทุกวัน
# ============================================================================
# รันบนเครื่องที่เป็นฐานข้อมูล ในนามผู้ใช้ postgres
#
# ⛔⛔ ทำไมต้องสำรอง และทำไมมันสำคัญกว่าที่คิด
#
#    state หาย ≠ ข้อมูลหาย แต่คือ **Terraform ลืมว่าอะไรเป็นของมัน**
#    ผลที่ตามมาเจ็บกว่า เพราะ plan รอบถัดไปจะเห็นว่า "ยังไม่มีอะไรเลย"
#    แล้วเสนอ **สร้างทุกอย่างใหม่** ทั้งที่ของเดิมยังรันอยู่
#    ได้เครื่องซ้ำ ได้บิลซ้ำ และของเดิมกลายเป็นของกำพร้าที่ไม่มีใครดูแล
#
#    ⭐ ที่แย่กว่านั้นคือ import กลับเข้ามาใหม่ต้องรู้ id ของทุกชิ้น
#      ซึ่งถ้ามีทรัพยากรห้าสิบชิ้น คือการนั่งไล่ทีละชิ้นจากหน้าเว็บ
#
# ⚠️ ข้อจำกัดที่ต้องรู้: backend แบบ pg ไม่เก็บประวัติเวอร์ชันให้
#    ต่างจาก S3 ที่เปิด versioning แล้วย้อนกลับได้ทุกครั้งที่เขียน
#    ไฟล์สำรองรายวันนี้จึงเป็นสิ่งเดียวที่ทำหน้าที่นั้น
# ============================================================================
set -euo pipefail

# ⚠️ cron รันจากโฟลเดอร์ปัจจุบันของผู้เรียก ซึ่งผู้ใช้ postgres อาจอ่านไม่ได้
#    ทำให้ find ล้มตอนจะกลับเข้าโฟลเดอร์เดิม แม้งานหลักจะสำเร็จไปแล้ว
#    ย้ายไปยืนที่ / ก่อน ตัดปัญหาทั้งหมด
cd /

DIR=/var/backups/tfstate
KEEP_DAYS=14

mkdir -p "$DIR"
chmod 700 "$DIR"

pg_dump terraform_state | gzip > "$DIR/tfstate-$(date +%Y%m%d-%H%M).sql.gz"
chmod 600 "$DIR"/*.gz

# ⚠️ ของเก่ากว่าสองสัปดาห์แทบไม่มีประโยชน์ เพราะโครงสร้างเปลี่ยนไปแล้ว
#    และการเก็บไว้นานโดยไม่จำเป็น คือการเพิ่มที่ที่ความลับรั่วได้
find "$DIR" -name "tfstate-*.sql.gz" -mtime "+$KEEP_DAYS" -delete
